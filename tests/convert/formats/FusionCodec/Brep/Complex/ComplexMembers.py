def ComplexMember(Relative: str, Suffix: str, Digest: str) -> bytes:
    with ZipFile(KRepoRoot / Relative) as Archive:
        Names = tuple(
            EntryName
            for EntryName in Archive.namelist()
            if EntryName.endswith("." + Suffix)
        )
        if len(Names) != 1:
            raise ValueError("Complex geometry fixture must hold one member")
        Payload = Archive.read(Names[0])
    if HashBytes(Payload).hexdigest() != Digest:
        raise ValueError("Complex geometry fixture digest changed")
    return Payload
