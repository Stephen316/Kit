# the public information table and internal content manager use separate enum domains
UNIT_PROPERTIES = ("SW_UnitsLinear", "SW_UnitSystem", "SW_UnitsMassPropMass")
UNIT_WITNESSES = {(0, 5, 2): (0, 4, 1), (3, 3, 4): (3, 2, 3)}


# join the named public XML unit fields without guessing a numeric conversion rule
def CheckContentUnits(Archive, State, Native):
    Root = fromstring(Archive.require("docProps/ISolidWorksInformation.xml"))
    Values = []
    for Name in UNIT_PROPERTIES:
        (Property,) = tuple(
            Row for Row in Root.iter("property") if Row.get("name") == Name
        )
        (Typed,) = Property
        require(
            Typed.tag
            == "{http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes}i4",
            "typed public unit property",
        )
        Values.append(int(Typed.text))
    PublicUnits = tuple(Values)
    require(
        PublicUnits[1] == Native["units_code"]
        and UNIT_WITNESSES[PublicUnits] == State.Units,
        "archive and independent native/typed information unit observations agree",
    )


# check the matching header and reached config and native result body
def CheckContentContext(Archive, State, Native, Generation):
    Cursor, Logs = ReadHeaderLogs(Archive.require("Header2"), Generation)
    ReadHeaderSelf(Cursor, Generation)
    Header = ReadHeaderTail(Cursor, Generation)
    require(
        State.Clock
        == ContentClock(Header.CreationTime, Header.UpdateTime, Logs.UpdateStamp),
        "content clocks match the independently reached header fields",
    )
    Model = NativePartModel(Archive, None)
    ConfigId = Model.active_configuration_id
    (Config,) = Model.configurations
    require(
        Config.configuration_id == ConfigId
        and Config.name == State.ConfigName == Native["configuration"],
        "content owns the active saved configuration and measured configuration",
    )
    CheckContentUnits(Archive, State, Native)
    ConfigStream = f"Contents/Config-{ConfigId}"
    ConfigData = Archive.require(ConfigStream)
    _, Walk = ReadOrdinaryMap(ConfigData, Generation)
    RegionIds = tuple(Row[0] for Group in Walk["regions"] for Row in Group)
    OwnerIds = () if State.Body is None else (State.Body.AtomId,)
    require(
        RegionIds == OwnerIds and len(OwnerIds) == Native["body_count"],
        "saved body folder IDs agree with typed config regions and native body count",
    )
    if State.Body is not None:
        Resolved = Archive.require(f"{ConfigStream}-ResolvedFeatures")
        Boss = ReadRectPart(ConfigData, Resolved, Generation).Boss
        require(
            Boss is not None and Boss["name"] == State.Body.Name and State.Body.Visible,
            "saved visible solid folder belongs to the reached ordinary boss",
        )


# verify complete generated bytes in the independent positive and negative shape controls
def CheckFresh(Generation):
    Fresh = ContentState(
        "Alternate \u0394",
        "Material <not specified>",
        "Steel",
        ORDINARY_FLAGS,
        UNSET_DENSITY,
        (3, 2, 3),
        ContentClock(1_700_000_000, 1_700_000_007, 149),
        ContentBody(701, "Renamed boss", False),
    )
    Payload = EncodeContentManager(Generation, Fresh)
    SketchOnly = replace(Fresh, Body=None)
    EmptyPayload = EncodeContentManager(Generation, SketchOnly)
    require(
        ReadContentManager(Generation, Payload) == Fresh
        and ReadContentManager(Generation, EmptyPayload) == SketchOnly,
        "fresh labels header values and hidden or absent body survive serialization",
    )

    Cursor = ArchiveCursor(Payload, 0, 1, {}, {})
    _, ConfigName, _, _ = ReadContentStart(Cursor)
    Cursor.ReadInts("<I")
    CheckConfigKey(Cursor, ConfigName)
    Cursor.ReadText()
    Cursor.ReadInts("<3i")
    ReadFolderCount(Cursor, ConfigName, "<I")
    Cursor.ReadInts("<i")
    Cursor.ReadText()
    CountStart = Cursor.Offset
    ReadFolderCount(Cursor, ConfigName, "<i")
    OwnerStart = Cursor.Offset
    WrongOwner = bytearray(Payload)
    pack_into("<i", WrongOwner, OwnerStart, 702)
    WrongCount = bytearray(Payload)
    Cursor.Offset = CountStart
    CheckConfigKey(Cursor, ConfigName)
    pack_into("<i", WrongCount, Cursor.Offset + 4, 0)

    for Bad in (Payload[:-1], Payload + bytes(1), bytes(WrongOwner), bytes(WrongCount)):
        try:
            ReadContentManager(Generation, Bad)
        except ValueError:
            continue
        raise ValueError("the content-manager reader accepted a malformed member")
    return sha256(Payload).hexdigest(), sha256(EmptyPayload).hexdigest()


# every receipt row binds the generated bytes to the reached source and native observations
def Report():
    Generation = KPartGeneration
    Cases = {}
    for Recipe, Asset, Source, _, Native in principal_captures():
        Archive = SldprtArchive.from_bytes(Source, Asset["path"])
        require(
            ContainerMo(Archive.streams) == Generation,
            "generation-19000 content member",
        )
        NativePayload = Archive.require(CONTENT_MANAGER)
        State = ReadContentManager(Generation, NativePayload)
        CheckContentContext(Archive, State, Native, Generation)
        Output = EncodeContentManager(Generation, State)
        require(
            Output == NativePayload,
            "the entire generated content member matches its source",
        )
        Cases[Asset["sha256"]] = {
            "recipe": Recipe,
            "payload_bytes": len(Output),
            "payload_sha256": sha256(Output).hexdigest(),
            "state": asdict(State),
        }
    require(
        sorted(Row["payload_bytes"] for Row in Cases.values()) == [421] * 6 + [463] * 8,
        "all fourteen distinct sealed content members",
    )
    Fresh, Empty = CheckFresh(Generation)
    return {
        "capture_revision": CAPTURE_REVISION,
        "replay_sha256": sha256(
            json.dumps(Cases, separators=(",", ":"), sort_keys=True).encode()
        ).hexdigest(),
        "fresh_body_sha256": Fresh,
        "fresh_sketch_sha256": Empty,
        "negative_controls": 4,
        "cases": Cases,
    }


if __name__ == "__main__":
    print(json.dumps(Report(), sort_keys=True))
