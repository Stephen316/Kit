from hashlib import sha256
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
CAPTURE_REVISION = "466dcb172dfa3803463e07ccde963ba01671d200"
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "re/automation")]

from DefinitionReadback import ReadModernPartDefinition
from DefinitionStream import EncodeModernPartDefinition
from SolidworksCensusInputs import capture_inputs
from convert.adapters.solidworks.Container.Archive import ArchiveError, ContainerMo
from convert.adapters.solidworks.Container.ArchiveCheck import RequireArch
from convert.adapters.solidworks.Container.Container import SldprtArchive


# every saved stream must match its independently framed reconstruction through EOF
def verify_definition():
    rows, _ = capture_inputs(ROOT, CAPTURE_REVISION)
    captures = {}
    views = set()
    font_orders = set()
    for _, item, data, _, _ in rows:
        archive = SldprtArchive.from_bytes(data, item["path"])
        generation = ContainerMo(archive.streams)
        RequireArch(generation, 19000, "Definition verification generation")
        saved = archive.require("Contents/Definition")
        decoded = ReadModernPartDefinition(saved, 19000)
        rebuilt = EncodeModernPartDefinition(
            UserName=decoded.UserName,
            PreambleView=decoded.PreambleView,
            Camera=decoded.Camera,
            Views=decoded.Views,
            Attachment=decoded.Attachment,
            AppearanceCounter=decoded.AppearanceCounter,
            TerminalValue=decoded.TerminalValue,
            Bindings=decoded.Bindings,
        )
        if rebuilt != saved:
            offset = next(
                (
                    position
                    for position, pair in enumerate(zip(rebuilt, saved))
                    if pair[0] != pair[1]
                ),
                min(len(rebuilt), len(saved)),
            )
            raise ArchiveError(
                f"Definition reconstruction differs at {offset} in {item['path']} "
                f"({len(rebuilt)} generated bytes, {len(saved)} saved)"
            )
        views.add(decoded.PreambleView is not None)
        font_orders.add(tuple(binding.annotation for binding in decoded.Bindings))
        captures[item["sha256"]] = sha256(saved).hexdigest()
    return {
        "capture_revision": CAPTURE_REVISION,
        "captures": captures,
        "preamble_view_forms": len(views),
        "line_font_orders": len(font_orders),
    }


if __name__ == "__main__":
    print(json.dumps(verify_definition(), sort_keys=True))
